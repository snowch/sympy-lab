import fs from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {esc,header,footer,renderHome,renderLesson} from './layout.mjs';
import {renderNotes} from './notes.mjs';
const course=JSON.parse(await fs.readFile('src/course.json','utf8'));
const {lessons,modules,applications}=course,all=[...lessons,...applications];
await fs.rm('dist',{recursive:true,force:true});await fs.mkdir('dist/lessons',{recursive:true});
execFileSync('python3',['scripts/execute.py'],{stdio:'inherit'});
const worked=JSON.parse(await fs.readFile('.cache/worked.json','utf8'));
const assets={};for(const file of ['app.js','style.css','worker.js','editor.mjs'])assets[file]=await fs.readFile('src/'+file,'utf8');
assets['style.css']+='\n'+await fs.readFile('src/quiet.css','utf8');
const version=createHash('sha256').update(Object.values(assets).join('\n')).digest('hex').slice(0,12);
for(const[file,content]of Object.entries(assets)){
 await fs.writeFile('dist/'+file,content);
 const dot=file.lastIndexOf('.'),name=file.slice(0,dot)+'.'+version+file.slice(dot);
 const published=file==='app.js'?content.replace("'./editor.mjs'","'./editor."+version+".mjs'").replace("'worker.js'","'worker."+version+".js'"):content;
 await fs.writeFile('dist/'+name,published);
}
await fs.mkdir('dist/vendor',{recursive:true});
for(const file of ['katex.mjs','katex.min.css'])await fs.copyFile('node_modules/katex/dist/'+file,'dist/vendor/'+file);
await fs.cp('node_modules/katex/dist/fonts','dist/vendor/fonts',{recursive:true});
await fs.copyFile('node_modules/katex/LICENSE','dist/vendor/KATEX-LICENSE.txt');
await fs.copyFile('src/course.json','dist/course.json');await fs.cp('src/fonts','dist/fonts',{recursive:true});
await fs.cp('python','dist/python',{recursive:true});
await fs.writeFile('dist/worked-environment.json',JSON.stringify(worked.environment,null,2));
await fs.writeFile('dist/.nojekyll','');
await fs.writeFile('dist/favicon.svg','<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 36 36"><rect width="36" height="36" rx="10" fill="#176b52"/><path d="M24 9H12l7 9-7 9h12" fill="none" stroke="white" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/></svg>');
const shell=(title,body,p='')=>`<!doctype html><html lang="en-GB"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="light dark"><meta name="description" content="Learn SymPy through 48 short Python investigations and four integrated workshops. Optional maths refreshers, exact symbolic results and a clear learning path."><title>${esc(title)} · SymPy Lab</title><link rel="icon" href="${p}favicon.svg"><link rel="stylesheet" href="${p}vendor/katex.min.css"><link rel="stylesheet" href="${p}style.${version}.css"><script>try{document.documentElement.dataset.theme=localStorage.getItem('syl:theme')||'light'}catch{}</script><script type="module" src="${p}app.${version}.js"></script></head><body>${header(p)}${body}${footer(p)}</body></html>`;
await fs.writeFile('dist/index.html',shell('Make the maths make sense',renderHome(course,worked.lessons[lessons[3].slug])));
for(const[i,l]of all.entries()){
 const code=await fs.readFile('python/'+l.code,'utf8'),record=worked.lessons[l.slug],figures=[];
 for(const[j,svg]of record.figures.entries()){
  const filename=l.slug+'-'+j+'.svg';await fs.writeFile('dist/lessons/'+filename,svg);
  figures.push(`<figure class="worked-figure"><img class="plot" src="${filename}" alt="Plot generated by the executed Python example. Read its labelled axes and the lesson explanation together." loading="lazy"><figcaption><a href="${filename}" target="_blank" rel="noopener">Open full-size figure ↗</a></figcaption></figure>`);
 }
 await fs.writeFile('dist/lessons/'+l.slug+'.html',shell(l.title,renderLesson({lesson:{...l,worked:record},index:i,lessons,modules,applications,code,figures}),'../'));
}
await fs.writeFile('dist/field-notes.html',shell('Field notes & maths map',renderNotes(course)));
execFileSync('python3',['scripts/prepare-runtime.py'],{stdio:'inherit'});
await fs.rm('.preview/sympy-lab',{recursive:true,force:true});await fs.mkdir('.preview/sympy-lab',{recursive:true});
await fs.cp('dist','.preview/sympy-lab',{recursive:true});
console.log(`Built ${lessons.length} lessons, ${applications.length} workshops, field notes and a self-hosted SymPy runtime.`);
